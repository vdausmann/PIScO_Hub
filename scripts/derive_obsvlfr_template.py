#!/usr/bin/env python3
"""Derive the remote-EcoTaxa profile template from the canonical one.

`profile_template.json` targets an EcoTaxa that shares a filesystem with the
Hub: the export is imported where it already sits, and a final step writes ViT
embeddings into its Postgres so "similar to" works.

Neither holds for a public instance such as ecotaxa.obs-vlfr.fr, which shares
no disk with us and exposes no endpoint for writing feature vectors (checked
against its OpenAPI: nothing accepts obj_cnn_features_vector). So the remote
route differs in exactly two ways:

* the import step uploads the archive first (``uploadArchive``);
* the ``pisco_ecotaxa_features`` step is dropped - left in, it would never
  schedule, because no machine here carries the ``ecotaxa`` tag, and the
  workflow would sit Pending forever rather than finish.

The steps themselves must not drift from the canonical chain, which is why
this is generated rather than copied by hand. Re-run it whenever
profile_template.json changes:

    python3 scripts/derive_obsvlfr_template.py
"""

import collections
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SOURCE = HERE / "examples" / "profile_template.json"
TARGET = HERE / "examples" / "profile_obsvlfr.json"

# Where this deployment keeps the public instance's credentials. A path, not a
# secret: task settings are rendered to disk in plain text, so the password
# itself must never be one.
CREDENTIALS = "/home/veit/.config/pisco/ecotaxa-online.json"
ECOTAXA_URL = "https://ecotaxa.obs-vlfr.fr"  # no /api: the tool appends it

# The ATAIR-trained pair. The binary stage is the one that sees every object.
MODELS = {
    "binary_model": "/home/veit/PIScO_dev/ViT_ATAIIR2604_NorthSea_binary/best_model",
    "taxon_model": "/home/veit/PIScO_dev/ViT_ATAIIR2604_NorthSea_multiclass/best_model",
    # The checkpoint the ATAIR v5a numbers were produced with - not the
    # noGrad ablation the canonical template defaults to. Absolute, because it
    # lives in underwater-lucyd rather than the deconvolution tool's models/.
    "deconv_model": "/home/veit/PIScO_dev/underwater-lucyd/models/"
                    "lucyd-edof-plankton_v5a_20260807.pth",
}


def main():
    doc = json.loads(SOURCE.read_text(), object_pairs_hook=collections.OrderedDict)

    doc["name"] = "profile_obsvlfr"
    doc["description"] = (
        "One PISCO profile, camera output to the PUBLIC EcoTaxa "
        "(ecotaxa.obs-vlfr.fr). Same chain as 'profile' but the archive is "
        "uploaded to EcoTaxa's FTP drop instead of being imported in "
        "place, and the embedding step is dropped - that instance has no API "
        "for writing feature vectors, so similarity search there uses "
        "EcoTaxa's own deep features. Generated by "
        "scripts/derive_obsvlfr_template.py; edit profile_template.json, not "
        "this file."
    )

    # Drop the features step. It is last and nothing references it, so no
    # $from index needs renumbering - assert rather than trust that.
    features = [i for i, t in enumerate(doc["tasks"])
                if t["tool"] == "pisco_ecotaxa_features"]
    assert features == [len(doc["tasks"]) - 1], (
        f"pisco_ecotaxa_features is at {features}, not last; dropping it would "
        f"renumber the $from references. Fix this script before regenerating.")
    dropped = doc["tasks"].pop()
    for task in doc["tasks"]:
        for value in task["settings"].values():
            ref = value.get("$from") if isinstance(value, dict) else None
            assert not ref or ref.get("task") != features[0], \
                "a step still references the dropped features task"

    imports = [t for t in doc["tasks"] if t["tool"] == "pisco_ecotaxa_import"]
    assert len(imports) == 1, f"expected one import step, found {len(imports)}"
    imports[0]["settings"].update(collections.OrderedDict([
        ("url", ECOTAXA_URL),
        ("uploadArchive", True),
        ("credentialsPath", CREDENTIALS),
    ]))

    params = doc["params_schema"]["properties"]
    for key, value in MODELS.items():
        assert key in params, f"{key} is no longer a template parameter"
        params[key]["default"] = value
    # The PCA basis only fed the dropped step.
    params.pop("pca_path", None)
    doc["params_schema"]["required"] = [
        r for r in doc["params_schema"].get("required", []) if r != "pca_path"]

    for variant in doc.get("variants", []):
        variant["name"] = variant["name"].replace("profile", "profile_obsvlfr", 1)
        variant.get("defaults", {}).pop("pca_path", None)

    # indent=2 and ensure_ascii=False: the same formatting as the source,
    # so a diff between the two templates shows only real differences.
    TARGET.write_text(
        json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {TARGET.relative_to(HERE)}")
    print(f"  dropped step: {dropped['tool']}")
    print(f"  steps: {len(doc['tasks'])}")
    print(f"  variants: {[v['name'] for v in doc.get('variants', [])]}")


if __name__ == "__main__":
    main()
